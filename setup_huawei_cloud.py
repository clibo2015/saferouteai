def main():
    """Main setup function"""
    print_banner()
    
    # Check prerequisites
    env_exists = check_prerequisites()
    
    # Get user choice
    if env_exists:
        choice = input("🤔 .env file exists. Update it? (y/N): ").strip().lower()
        if choice not in ['y', 'yes']:
            print("   Skipping credential update...")
            estimate_costs()
            show_next_steps()
            return
    
    # Get credentials
    try:
        credentials = get_user_credentials()
        
        # Validate credentials are not empty
        if not all(credentials.values()):
            print("❌ Error: All credentials are required")
            sys.exit(1)
        
        # Update .env file
        update_env_file(credentials)
        
        # Show cost estimates
        estimate_costs()
        
        # Show next steps
        show_next_steps()
        
        print("✅ Setup completed successfully!")
        print("🚀 Your SafeRouteAI is ready for Huawei Cloud production!")
        
    except KeyboardInterrupt:
        print("\n❌ Setup cancelled by user")
        sys.exit(1)
    except Exception as e:
        print(f"❌ Error during setup: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()