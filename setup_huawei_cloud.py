def print_banner():
    """Print setup banner"""
    print("=" * 60)
    print("🚀 SafeRouteAI - Huawei Cloud Production Setup")
    print("💰 $100 Coupon Optimization Guide")
    print("=" * 60)
    print()

def check_prerequisites():
    """Check if required files and dependencies exist"""
    print("📋 Checking prerequisites...")
    
    # Check if .env exists
    env_exists = Path(".env").exists()
    env_example_exists = Path(".env.example").exists()
    
    print(f"   ✅ .env.example found: {env_example_exists}")
    print(f"   {'✅' if env_exists else '❌'} .env file: {'Found' if env_exists else 'Missing'}")
    
    if not env_exists and env_example_exists:
        print("   💡 Run: cp .env.example .env")
        print("   💡 Then edit .env with your Huawei Cloud credentials")
    
    # Check Python dependencies
    try:
        import requests
        print("   ✅ requests library: Available")
    except ImportError:
        print("   ❌ requests library: Missing (run: pip install requests)")
    
    print()
    return env_exists

def get_user_credentials():
    """Interactive credential collection"""
    print("🔐 Huawei Cloud Credentials Setup")
    print("Get these from: https://console.huaweicloud.com → My Credentials → Access Keys")
    print()
    
    credentials = {}
    
    # Get credentials interactively
    credentials['ak'] = input("Enter your Access Key (AK): ").strip()
    credentials['sk'] = input("Enter your Secret Key (SK): ").strip()
    credentials['project_id'] = input("Enter your Project ID: ").strip()
    credentials['region'] = input("Enter region [af-south-1]: ").strip() or "af-south-1"
    
    return credentials

def update_env_file(credentials: Dict[str, str]):
    """Update .env file with credentials"""
    print("📝 Updating .env file...")
    
    env_content = f"""# SafeRouteAI - Huawei Cloud Production Configuration
# Generated by setup_huawei_cloud.py

# Huawei Cloud Credentials
HUAWEI_CLOUD_AK={credentials['ak']}
HUAWEI_CLOUD_SK={credentials['sk']}
HUAWEI_CLOUD_PROJECT_ID={credentials['project_id']}
HUAWEI_CLOUD_REGION={credentials['region']}

# API Configuration
API_HOST=0.0.0.0
API_PORT=8000

# Production Mode (set to false to use real Huawei Cloud services)
DEMO_MODE=false

# OBS Configuration
OBS_BUCKET_NAME=saferoute-ai-data

# Cost Optimization Settings
MAX_BUDGET_USD=100
COST_ALERT_THRESHOLDS=50,75,90
AUTO_SCALE_ENABLED=true

# Competition Settings
COMPETITION_MODE=true
REAL_DATA_INTEGRATION=true
"""
    
    with open(".env", "w") as f:
        f.write(env_content)
    
    print("   ✅ .env file updated successfully")
    print()

